// Real installed-Pi compatibility + read-only vault smoke check. No model calls.
import assert from 'node:assert/strict';
import * as path from 'node:path';
import * as os from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { piPackageDir } from '../test/helpers/pi-runtime.mjs';
import { loadConfig } from '../src/config.ts';
import { Vault } from '../src/vault.ts';
import { emptyGrants } from '../src/policy.ts';
import { search } from '../src/search.ts';
import { resolveLink } from '../src/links.ts';
const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const sdk = await import(pathToFileURL(path.join(piPackageDir(), 'dist/index.js')));
const agentDir = sdk.getAgentDir();
const cwd = process.argv.includes('--global') ? os.tmpdir() : project;
const settings = sdk.SettingsManager.create(cwd, agentDir, { projectTrusted: true });
const loader = new sdk.DefaultResourceLoader({ cwd, agentDir, settingsManager: settings });
await loader.reload();
assert.deepEqual(loader.getExtensions().errors, []);
const extensions = loader.getExtensions().extensions;
const tools = extensions.flatMap(e => [...e.tools.keys()]);
for (const name of ['quiz', 'ask_user_question', 'subagent_spawn', 'vault_search', 'learning_record_assessment']) assert.ok(tools.includes(name), `Missing ${name}`);
assert.equal(new Set(tools).size, tools.length, 'Tool name collision');
const skills = loader.getSkills().skills.map(s => s.name);
for (const name of ['teach', 'visualize', 'obsidian-learning']) assert.ok(skills.includes(name), `Missing ${name}`);
const cfg = loadConfig();
const vault = new Vault(cfg, emptyGrants()); vault.refresh(true);
const index = [...vault.readableNotes()].find(n => n.name === 'Aritmetica Modulare');
assert.ok(index, 'Real modular arithmetic index');
const links = index.parsed.links.map(l => resolveLink(vault, index.path, l));
assert.ok(links.some(l => l.status === 'resolved'));
assert.ok(search(vault, 'piccionaia pigeonhole').some(h => h.kind === 'atomic'));
assert.ok(search(vault, 'CCIT piano').some(h => h.kind === 'source'));
console.log(JSON.stringify({ cwd, pi: JSON.parse((await import('node:fs')).readFileSync(path.join(piPackageDir(), 'package.json'), 'utf8')).version, extensions: extensions.length, tools: tools.length, skills: skills.length, readableNotes: vault.readableNotes().length, indexLinks: links.length, resolvedIndexLinks: links.filter(l => l.status === 'resolved').length, vaultWrites: 0 }, null, 2));
